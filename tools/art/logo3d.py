#!/usr/bin/env python3
"""logo3d.py - the Ultimate build's 3D title logo: data/logo3d.asm.

    python3 tools/art/logo3d.py

Reads the title's pixel-art logo ("NOT 1942" and "DX", +logo_px rows in
data/title.asm) and turns it into extruded blocks for src/title3d.asm:
each run of '#' in a row is merged with identical runs in the rows below
into one rectangle, and each rectangle becomes a box ZDEPTH units deep.
Object units: one logo pixel = 1 unit; x runs -XHALF..XHALF (column
edges), y down, "NOT 1942" above "DX".

Also writes the tables the renderer needs:
  t3_sin      sin(i * 360 / 256) * 127, signed bytes (cos = sin + 64)
  t3_stab     the perspective scale: screen pixels per unit (8.8) at
              depth index i, for depth d = (i - STAB_MID) * 64 / 128 units
              in front of / behind the logo's centre plane
"""
import math, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, "data", "title.asm")
OUT = os.path.join(ROOT, "data", "logo3d.asm")

UNIT_PX = 4          # screen pixels per unit at the centre plane
DIST = 120           # camera distance, in units, to the centre plane
ZDEPTH = 4           # box depth in units (front at -2, back at +2)
GAP = 2              # rows between "NOT 1942" and "DX"
STAB_MID = 80        # t3_stab index of depth 0 (d * 128 / 64 + STAB_MID)
STAB_LEN = 161


def logo_rows(label):
    txt = open(SRC).read()
    block = txt.split(label + "\n", 1)[1].split("+logo_end", 1)[0]
    return re.findall(r'\+logo_px "([#.]+)"', block)


def rects(rows):
    """Greedy: runs of '#' per row, each merged downwards with identical
    runs in the following rows. -> [(col0, col1_excl, row0, row1_excl)]"""
    runs = []
    for r, line in enumerate(rows):
        for m in re.finditer(r"#+", line):
            runs.append((m.start(), m.end(), r))
    used, out = set(), []
    for a, b, r in runs:
        if (a, b, r) in used:
            continue
        r1 = r + 1
        while (a, b, r1) in {(x0, x1, rr) for x0, x1, rr in runs}:
            used.add((a, b, r1))
            r1 += 1
        out.append((a, b, r, r1))
    return out


def main():
    logo, dx = logo_rows("title_logo"), logo_rows("title_dx")
    lw, dw = len(logo[0]), len(dx[0])
    xhalf = lw // 2
    h = len(logo) + GAP + len(dx)
    ytop = -(h // 2)
    boxes = []
    for a, b, r0, r1 in rects(logo):
        boxes.append((a - xhalf, b - xhalf, ytop + r0, ytop + r1))
    dxoff = -(dw // 2)
    for a, b, r0, r1 in rects(dx):
        y = ytop + len(logo) + GAP
        boxes.append((a + dxoff, b + dxoff, y + r0, y + r1))
    boxes.sort()
    xmin = min(b[0] for b in boxes)
    xmax = max(b[1] for b in boxes)
    assert max(b[1] - b[0] for b in boxes) <= 10, "a box too wide for the span filler"

    sin = [round(127 * math.sin(i * 2 * math.pi / 256)) for i in range(256)]
    stab = []
    for i in range(STAB_LEN):
        d = (i - STAB_MID) * 64 / 128            # units
        s = UNIT_PX * DIST / (DIST + d)
        stab.append(min(65535, round(s * 256)))

    L = ["; data/logo3d.asm: generated by tools/art/logo3d.py from data/title.asm.",
         "; Don't edit. The Ultimate build's 3D title logo (src/title3d.asm):",
         f"; {len(boxes)} boxes, x {xmin}..{xmax}, y {ytop}..{ytop + h}, {ZDEPTH} units deep.",
         f"T3_BOXES   = {len(boxes)}",
         f"T3_XMIN    = {xmin}            ; the leftmost column edge (units)",
         f"T3_XCOUNT  = {xmax - xmin + 1}            ; column edges xmin..xmax",
         f"T3_ZHALF   = {ZDEPTH // 2}             ; front at -ZHALF, back at +ZHALF",
         f"T3_STABMID = {STAB_MID}",
         f"T3_STABLEN = {STAB_LEN}",
         "; boxes, sorted by left edge: column index (x - T3_XMIN) of the left and",
         "; right edges, and the top and bottom rows (signed units, bottom exclusive)"]
    for name, k in (("t3_bx0", 0), ("t3_bx1", 1)):
        L.append(f"{name:10s} !byte " + ", ".join(str(b[k] - xmin) for b in boxes))
    for name, k in (("t3_by0", 2), ("t3_by1", 3)):
        L.append(f"{name:10s} !byte " + ", ".join(f"{b[k] & 0xff}" for b in boxes))
    L.append("t3_sin     ; sin(i * 360 / 256) * 127")
    for i in range(0, 256, 16):
        L.append("        !byte " + ", ".join(f"{v & 0xff:3d}" for v in sin[i:i + 16]))
    L.append(f"t3_stab_lo ; pixels per unit (8.8) at depth index i (d = (i - {STAB_MID}) / 2 units)")
    for i in range(0, STAB_LEN, 16):
        L.append("        !byte " + ", ".join(f"{v & 0xff:3d}" for v in stab[i:i + 16]))
    L.append("t3_stab_hi")
    for i in range(0, STAB_LEN, 16):
        L.append("        !byte " + ", ".join(f"{v >> 8:3d}" for v in stab[i:i + 16]))
    open(OUT, "w").write("\n".join(L) + "\n")
    print(f"logo3d: {len(boxes)} boxes, x {xmin}..{xmax}, y {ytop}..{ytop + h} -> {OUT}")


if __name__ == "__main__":
    main()
